def save_feedback(req_id, requirement, code,
                  ai_verdict, correct_verdict):

    feedback = pd.DataFrame([{
        "req_id": req_id,
        "requirement": requirement,
        "code": code,
        "ai_verdict": ai_verdict,
        "correct_verdict": correct_verdict
    }])

    if os.path.exists(FEEDBACK_FILE):
        feedback.to_csv(
            FEEDBACK_FILE,
            mode="a",
            header=False,
            index=False
        )
    else:
        feedback.to_csv(
            FEEDBACK_FILE,
            index=False
        )

    print("Human correction saved!")

def get_feedback_examples(limit=3):

    if not os.path.exists(FEEDBACK_FILE):
        return ""

    df = pd.read_csv(FEEDBACK_FILE)

    examples = ""

    for _, row in df.tail(limit).iterrows():

        examples += f"""
        Previous human correction:

        Requirement: {row['requirement']}
        Code: {row['code']}
        AI originally said: {row['ai_verdict']}
        Human corrected it to: {row['correct_verdict']}

        """

    return examples

