def evidence_guard(review, code):

    code_lines = [line.strip() for line in code.splitlines()]
    evidence = review.get("evidence_lines", [])

    if not isinstance(evidence, list) or not evidence:
        review["verdict"] = "HUMAN_REVIEW"
        review["confidence"] = 0.0
        return review

    for line in evidence:
        if not isinstance(line, str) or line.strip() not in code_lines:
            review["verdict"] = "HUMAN_REVIEW"
            review["confidence"] = 0.0
            return review

    return review

import json

SUPER = "nvidia/nemotron-3.5-super-vl-120b-a12b"

def split_requirements(spec_text):

    prompt = f"""
    You are DeltaZero's requirements splitter.

    Your job is to read a software project description
    and split it into individual requirements.

    PROJECT DESCRIPTION:
    {spec_text}

    Instructions:
    1. Identify each distinct requirement.
    2. Give every requirement a unique ID:
       REQ-001, REQ-002, REQ-003, etc.
    3. Each requirement should describe one
       specific feature or behavior.
    4. Keep requirements clear and concise.
    5. Do not invent requirements that aren't
       mentioned in the description.
    6. Preserve important conditions and constraints.
    7. Return ONLY valid JSON.

    Use this exact JSON structure:

    {{
        "requirements": [
            {{
                "req_id": "REQ-001",
                "requirement": "First requirement"
            }},
            {{
                "req_id": "REQ-002",
                "requirement": "Second requirement"
            }}
        ]
    }}
    """

    response = nemotron(prompt, SUPER)

    return json.loads(response)

LIGHTNING = "nvidia/nemotron-3.5-lightning-30b-a3b"
SUPER = "nvidia/nemotron-3.5-super-vl-120b-a12b"

def router(req_id, requirement, code, high_stakes=False):

    if high_stakes:
        model = SUPER
    else:
        model = LIGHTNING

    response = review_code(req_id, requirement, code, model)

    print("Model used:", model)
    print("Response:", repr(response))

    if response is None:
        raise ValueError(
            f"Model {model} returned None. Check review_code() and nemotron()."
        )

    review = json.loads(response)
    review = evidence_guard(review, code)

    if model == LIGHTNING and (
        review["confidence"] < 0.8
        or review["verdict"] == "HUMAN_REVIEW"
    ):
        model = SUPER

        response = review_code(req_id, requirement, code, model)

        print("Escalated to:", model)
        print("Response:", repr(response))

        if response is None:
            raise ValueError(
                f"Model {model} returned None."
            )

        review = json.loads(response)
        review = evidence_guard(review, code)

    review["model_used"] = model

    return review

import time

def timed_router(req_id, requirement, code, high_stakes=False):

    start = time.perf_counter()

    review = router(
        req_id,
        requirement,
        code,
        high_stakes=high_stakes
    )

    end = time.perf_counter()

    review["latency_seconds"] = round(end - start, 3)

    return review

